"""EDA 叙述报告生成器。

读取一次 EDA 运行产出的结构化结果（eda_summary.json / eda_recommendations.json /
data_quality.json 与可选的聚合审计 JSON），渲染成一份中文 EDA_REPORT.md。

设计原则：
- 纯函数，只读已有 JSON / plots 目录，绝不重算诊断。
- 复用 eda_recommendations.json 已算好的建议（阈值已在 recommendations.py 应用），
  本模块只负责"叙述解释"（平稳性方向、ARCH/White/BP 折中、FFT≈N 伪周期、谐波、
  BDS 警示、forecastability 语义等）。
- 输入缺失时优雅降级（省略对应内容而非报错）；eda_summary.json 缺失则放弃生成。
- 与 config / data_provider 解耦：cfg 与 aggregation_result 仅作字符串注解的鸭子类型，
  通过 getattr 防御式读取，不在运行期 import 它们。
"""
