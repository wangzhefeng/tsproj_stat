def build_title(ctx: dict) -> list[str]:
    name = ctx.get("data_name") or "时间序列"
    return [f"# {name} EDA 报告", ""]


def _exec_summary(ctx: dict) -> list[str]:
    s = ctx.get("summary") or {}
    rec = ctx.get("recommendations") or {}
    bullets: list[str] = []
    ts = _as_float(_sget(s, "decomposition", "trend_strength"))
    ss = _as_float(_sget(s, "decomposition", "seasonal_strength"))
    period = _sget(s, "decomposition", "period")
    if ts is not None:
        dominate = "由显著上升趋势主导" if ts >= 0.6 else "趋势成分明显" if ts >= 0.35 else "趋势成分较弱"
        head = f"- 序列{dominate}，趋势强度 **{_fmt_num(ts, 3)}**；"
        if ss is not None and period is not None:
            head += f"以配置周期 {int(period)} 的季节强度仅为 **{_fmt_num(ss, 3)}**，季节性较弱。"
        bullets.append(head)

    d = _sget(rec, "differencing", "recommended_d")
    big_d = _sget(rec, "differencing", "recommended_D")
    stat = _stationarity_by_name(s)
    if stat:
        bullets.append(
            "- 平稳性检验（ADF/PP/KPSS）一致指向"
            + ("非平稳" if d else "近似平稳")
            + f"，建议普通差分 `d={d}`、季节差分 `D={big_d}`。"
        )

    lb_p = _sget(s, "white_noise", "ljung_box_pvalue")
    if _as_float(lb_p) is not None:
        bullets.append(
            "- " + ("原序列存在很强的序列相关性，不是白噪声，历史信息具有预测价值；模型必须处理趋势与自相关。"
                    if _as_float(lb_p) < 0.05 else "序列接近白噪声，时间依赖结构较弱。")
        )

    arch_p = _sget(s, "heteroskedasticity", "arch_lm_pvalue")
    if _as_float(arch_p) is not None:
        bullets.append(
            "- ARCH-LM 检验" + ("显著，残差波动可能具有条件异方差（波动聚集）。" if _as_float(arch_p) < 0.05 else "不显著，未提示明显条件异方差。")
        )

    rec_period = _sget(rec, "seasonal_period", "recommended_period")
    fft = _sget(s, "cycle", "dominant_period_fft")
    if rec_period is not None or _is_fft_artifact(fft, ctx.get("n_samples")):
        part = f"自动周期建议给出 {int(rec_period)} 天候选（置信度低）。" if rec_period is not None else ""
        fft_part = "FFT 主周期接近样本长度，主要反映趋势或有限样本边界，不应直接解释为业务周期。" if _is_fft_artifact(fft, ctx.get("n_samples")) else ""
        bullets.append("- " + " ".join(p for p in (part, fft_part) if p))

    n_iqr = _sget(s, "outliers", "n_outliers_iqr")
    if n_iqr is not None:
        bullets.append(f"- 仅检测到 **{_fmt_int(n_iqr)}** 个异常点（异常率约 **{_fmt_pct(_sget(s, 'outliers', 'outlier_rate_iqr'), 2)}**），不支持大范围异常值替换。")

    cands = _sget(rec, "model_family", "candidates") or []
    if cands:
        bullets.append(f"- 建议优先比较的模型族：{', '.join(cands)}；模型选择以滚动回测为准。")

    return ["## 技术摘要", "", *bullets, ""]


def build_section_1(ctx: dict) -> list[str]:
    s = ctx.get("summary") or {}
    dq = ctx.get("data_quality") or {}
    agg = ctx.get("aggregation")
    target_freq = ctx.get("freq")
    rows: list[str] = []

    def add(label: str, value: Any):
        rows.append(f"| {label} | {value} |")

    if agg and agg.get("source_freq"):
        add("原始频率", _freq_zh(agg["source_freq"]) or agg["source_freq"])
    if target_freq:
        add("建模频率", (_freq_zh(target_freq) or target_freq) + "频")
    if agg and agg.get("method_zh"):
        add("日值定义", f"当日{agg['method_zh']}")
    tr_start = (agg.get("time_range_start") if agg else None) or _sget(dq, "time_range_start")
    tr_end = (agg.get("time_range_end") if agg else None) or _sget(dq, "time_range_end")
    if tr_start and tr_end:
        add("时间范围", f"{tr_start} 至 {tr_end}")
    if agg and agg.get("source_rows") is not None:
        add("原始记录数", _fmt_int(agg["source_rows"]))
    add("建模记录数", _fmt_int(ctx.get("n_samples") or _sget(dq, "clean_rows")))
    if agg and agg.get("inserted") is not None:
        add("补齐并填充的时间点", _fmt_int(agg["inserted"]))
    if agg and agg.get("dup") is not None:
        add("重复时间戳", _fmt_int(agg["dup"]))
    add("建模序列缺失率", _fmt_pct(_sget(s, "missing_rate", default=_sget(dq, "missing_ratio"))))

    lines = ["## 1. 数据口径与质量", ""]
    if rows:
        lines += ["| 项目 | 结果 |", "| --- | ---: |", *rows, ""]
    else:
        lines += ["（数据口径信息不足）", ""]

    if agg and agg.get("source_freq"):
        fill = agg.get("fill_method")
        weeks = agg.get("fill_weeks")
        fill_desc = {
            "seasonal_slot": f"`seasonal_slot`：对每个缺失时间点，使用前后 {weeks or 'N'} 周内相同星期与相同时刻的有效观测均值。",
            "linear": "`linear`：按时间线性插值。",
            "none": "`none`：不填充（缺失会直接暴露并在聚合时被严格校验拒绝）。",
        }.get(str(fill), f"`{fill}`")
        lines += [
            f"该序列由源频率 {_freq_zh(agg['source_freq']) or agg['source_freq']} 聚合而来，缺失值使用 {fill_desc}",
            "填充值并非真实测量值；涉及异常日、节假日或设备状态变化时，应回看原始高频序列与聚合审计。",
            "",
        ]
    elif agg is None:
        lines += ["本数据未启用频率聚合（直接以建模频率输入）。", ""]
    return lines


def build_section_2(ctx: dict, output_dir: Path) -> list[str]:
    s = ctx.get("summary") or {}
    rec = ctx.get("recommendations") or {}
    lines = [
        "## 2. 趋势与水平",
        "",
        f"均值为 **{_fmt_num(_sget(s, 'mean'))}**，标准差 **{_fmt_num(_sget(s, 'std'))}**，"
        f"最小值 **{_fmt_num(_sget(s, 'min'))}**，最大值 **{_fmt_num(_sget(s, 'max'))}**；"
        f"四分位区间 {_fmt_num(_sget(s, 'q1'))} 至 {_fmt_num(_sget(s, 'q3'))}。",
        f"偏度 **{_fmt_num(_sget(s, 'skewness'), 3)}**，"
        + ("整体分布近似对称；" if abs(_as_float(_sget(s, 'skewness')) or 0) < 0.5 else "分布存在偏态；")
        + f"峰度 **{_fmt_num(_sget(s, 'kurtosis'), 3)}**，"
        + ("较正态分布更平缓。" if (_as_float(_sget(s, 'kurtosis')) or 0) < 0 else "较正态分布更尖峭。"),
        "",
    ]
    ref = _plot_ref(output_dir, "series", "时序图")
    if ref:
        lines += [ref, ""]
    ts = _as_float(_sget(s, "decomposition", "trend_strength"))
    rstd = _sget(s, "decomposition", "residual_std")
    if ts is not None:
        lines.append(f"STL 分解的趋势强度为 **{_fmt_num(ts, 3)}**，绝大部分可解释变化来自长期水平变化。")
    if _as_float(rstd) is not None:
        mean_v = _as_float(_sget(s, "mean")) or 0.0
        pct = (rstd / mean_v * 100) if mean_v else None
        lines.append(
            f"同期残差标准差为 **{_fmt_num(rstd)}**"
            + (f"，约为均值的 {_fmt_pct(pct / 100)}，可作为去趋势、去季节后的噪声底盘参考。" if pct else "。")
        )
    lines.append("")
    ref = _plot_ref(output_dir, "trend", "趋势分量")
    if ref:
        lines += [ref, ""]
    detrend = _sget(rec, "preprocessing", "detrend_method")
    d = _sget(rec, "differencing", "recommended_d")
    lines.append(
        f"建模时应优先处理趋势。当前自动建议为 `detrend_method={detrend}`、差分 `d={d}`；"
        "实际实验中不应同时无条件叠加「线性去趋势」与「一阶差分」两种处理，应分别建立候选配置并通过滚动回测取舍。"
    )
    lines.append("")
    fb = _forecastability_note(_sget(s, "forecastability"))
    if fb:
        lines += [fb, ""]
    return lines


def build_section_3(ctx: dict, output_dir: Path) -> list[str]:
    s = ctx.get("summary") or {}
    rec = ctx.get("recommendations") or {}
    ss = _as_float(_sget(s, "decomposition", "seasonal_strength"))
    period = _sget(s, "decomposition", "period")
    lines = ["## 3. 季节性与周期", ""]
    if ss is not None:
        lines.append(f"以配置周期 {period} 进行 STL 分解时，季节强度为 **{_fmt_num(ss, 3)}**，" + (
            "明显低于趋势强度。" if ss < 0.35 else "存在不可忽视的季节结构。"))
    d_ch = _sget(s, "seasonal_diff", "D_ch")
    d_ocsb = _sget(s, "seasonal_diff", "D_ocsb")
