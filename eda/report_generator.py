AUTOGEN_MARKER = (
    "<!-- auto-generated by eda/report_generator.py; "
    "set eda_report_overwrite=true to regenerate -->"
)

_METHOD_ZH = {
    "max": "最大值",
    "mean": "均值",
    "sum": "合计",
    "min": "最小值",
    "median": "中位数",
}


# ##############################
# 基础工具：读取 / 格式化 / 取值
# ##############################
def _read_json(path: Path) -> dict | None:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def _is_num(x: Any) -> bool:
    if isinstance(x, bool) or not isinstance(x, (int, float)):
        return False
    try:
        return not (math.isnan(x) or math.isinf(x))
    except (TypeError, ValueError):
        return False


def _as_float(x: Any) -> float | None:
    return float(x) if _is_num(x) else None


def _sget(obj: dict | None, *keys: str, default: Any = None) -> Any:
    cur: Any = obj
    for k in keys:
        if not isinstance(cur, dict):
            return default
        cur = cur.get(k)
        if cur is None:
            return default
    return cur


def _fmt_num(x: Any, d: int = 2) -> str:
    v = _as_float(x)
    return f"{v:,.{d}f}" if v is not None else "—"


def _fmt_int(x: Any) -> str:
    try:
        return f"{int(x):,}"
    except (TypeError, ValueError):
        return "—"


def _fmt_pvalue(p: Any) -> str:
    v = _as_float(p)
    if v is None:
        return "—"
    if v <= 0:
        return "接近 0"
    if v < 1e-3:
        return f"{v:.2e}"
    return f"{v:.3f}"


def _fmt_pct(x: Any, d: int = 1) -> str:
    v = _as_float(x)
    return f"{v * 100:.{d}f}%" if v is not None else "—"


def _freq_zh(freq: Any) -> str:
    """把频率 token 翻成中文单位词，如 D→日、5min→5 分钟、1h→1 小时。"""
    if not freq:
        return ""
    s = str(freq).strip()
    low = s.lower()
    num = ""
    while low[:1].isdigit():
        num += low[0]
        low = low[1:]
    base = {
        "d": "日",
        "w": "周",
        "m": "月",
        "q": "季",
        "y": "年",
        "a": "年",
        "h": "小时",
        "min": "分钟",
        "t": "分钟",
        "s": "秒",
    }.get(low, low)
    return f"{num}{base}" if base else s


def _has_plot(output_dir: Path, name: str) -> bool:
    return (output_dir / "plots" / f"{name}.png").exists()


def _plot_ref(output_dir: Path, name: str, alt: str) -> str:
    return f"![{alt}](plots/{name}.png)" if _has_plot(output_dir, name) else ""


def _confidence_zh(conf: Any) -> str:
    c = str(conf).lower() if conf is not None else ""
    return {"high": "置信度高", "medium": "置信度中", "low": "置信度低"}.get(c, "")


def _stationarity_by_name(summary: dict | None) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for row in _sget(summary, "stationarity", default=[]) or []:
        if isinstance(row, dict) and row.get("name"):
            out[str(row["name"])] = row
    return out


# ##############################
# 叙述解释规则（这些不在任何 JSON，是本模块的价值所在）
# ##############################
def _stationarity_direction(name: str, row: dict | None) -> str:
    """ADF/PP 原假设=单位根；KPSS 原假设=平稳（方向相反）。"""
    if not row:
        return "检验缺失，无法判断"
    if row.get("ok") is False:
        return f"检验失败（{row.get('error') or '异常'}），无法判断"
    p = _as_float(row.get("pvalue"))
    if p is None:
        return "检验失败或样本不足，无法判断"
    if name == "kpss":
        return (
            "拒绝平稳原假设，支持非平稳判断"
            if p < 0.05
            else "不能拒绝平稳原假设"
        )
    # adf / pp
    return (
        "不能拒绝单位根，支持非平稳判断"
        if p > 0.05
        else "拒绝单位根，支持平稳判断"
    )


def _arch_vs_white(arch_p: Any, white_p: Any, bp_p: Any) -> str:
    a = _as_float(arch_p)
    if a is None:
        return "ARCH-LM 检验失败或样本不足（需差分后样本数 ≥ 20）"
    if a >= 0.05:
        return "未检测到显著的条件异方差"
    w = _as_float(white_p)
    b = _as_float(bp_p)
    fixed = (w is not None and w < 0.05) or (b is not None and b < 0.05)
    if fixed:
        return "存在异方差，其中部分可由时间趋势解释"
    return "更接近随时间聚集的波动（条件异方差），而非由某个简单解释变量驱动的固定形式异方差"


def _is_fft_artifact(fft_period: Any, n_samples: Any) -> bool:
    fp = _as_float(fft_period)
    n = _as_float(n_samples)
    if fp is None or n is None or n <= 0:
        return False
    return abs(fp - n) <= 1 or fp / n > 0.9


def _harmonic_note(acf_peak: Any, configured_period: Any) -> str:
    peak = _as_float(acf_peak)
    period = _as_float(configured_period)
    if peak is None or period is None or period <= 0:
        return ""
    k = peak / period
    if abs(k - round(k)) < 1e-6 and round(k) > 1:
        return f"该滞后恰为 {int(round(k))} 个整周期，更可能是周季节性的倍频/谐波，而非独立周期"
    return ""


def _ljung_box_note(lb_p: Any) -> str:
    p = _as_float(lb_p)
    if p is None:
        return "Ljung-Box 检验缺失。"
    if p < 0.05:
        return "明确拒绝白噪声假设，序列包含可利用的时间依赖结构，模型残差也必须重新检查自相关。"
    return "未拒绝白噪声假设，序列的时间依赖结构较弱。"


def _bds_note(p2: Any, p3: Any) -> str:
    a = _as_float(p2)
    b = _as_float(p3)
    if a is None and b is None:
        return "BDS 检验缺失。"
    if (a is not None and a < 0.05) or (b is not None and b < 0.05):
        return (
            "BDS 检验显著，序列不符合独立同分布假设，可能包含线性自相关之外的结构；"
            "但 BDS 本身不能证明具体的非线性机制，应在去趋势、差分并拟合均值模型后对残差再次检验。"
        )
    return "BDS 检验未拒绝独立同分布假设。"


def _forecastability_note(score: Any) -> str:
    v = _as_float(score)
    if v is None:
        return ""
    level = (
        "结构较简单、可预测性偏高"
        if v >= 0.4
        else "可预测性中等"
        if v >= 0.2
        else "可预测性偏低、噪声/随机成分较多"
    )
    return (
        f"forecastability={_fmt_num(score, 3)}（基于谱熵的相对评分，{level}）；"
        "该分数仅作模型复杂度的辅助信号，不可解释为可达预测准确率。"
    )


def _outlier_note(rate_iqr: Any, rate_z: Any) -> str:
    r = max(_as_float(rate_iqr) or 0.0, _as_float(rate_z) or 0.0)
    if r >= 0.03:
        return "异常率较高，建议结合业务事件与原始高频曲线核对后，再考虑针对性去噪。"
    return "异常率低，不建议默认启用全局去噪；应先定位异常日期、结合原始曲线确认其真实性。"


