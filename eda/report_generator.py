def _load_inputs(
    output_dir: Path,
    cfg: "AppConfig | None",
    aggregation_result: "AggregationResult | None",
    data_name: str | None,
) -> dict[str, Any]:
    summary = _read_json(output_dir / "eda_summary.json")
    recommendations = _read_json(output_dir / "eda_recommendations.json")
    data_quality = _read_json(output_dir / "data_quality.json")

    audit: dict | None = None
    if aggregation_result is not None:
        audit_path = getattr(aggregation_result, "audit_path", None)
        if audit_path:
            audit = _read_json(Path(audit_path))

    def cfg_get(name: str, default=None):
        return getattr(cfg, name, default) if cfg is not None else default

    agg_enabled = bool(cfg_get("aggregation_enabled", False)) or audit is not None
    method = _sget(audit, "config", "method") or cfg_get("aggregation_method")
    aggregation = None
    if audit is not None or agg_enabled:
        aggregation = {
            "source_freq": _sget(audit, "config", "source_freq") or cfg_get("aggregation_source_freq"),
            "method": method,
            "method_zh": _METHOD_ZH.get(str(method).lower(), str(method) if method else ""),
            "fill_method": _sget(audit, "config", "fill_method") or cfg_get("aggregation_fill_method"),
            "fill_weeks": _sget(audit, "config", "fill_weeks") or cfg_get("aggregation_fill_weeks"),
            "source_rows": _sget(audit, "source_rows"),
            "output_rows": _sget(audit, "output_rows"),
            "inserted": _sget(audit, "inserted_timestamp_count"),
            "filled": _sget(audit, "filled_value_count"),
            "dup": _sget(audit, "duplicate_timestamp_count"),
            "time_range_start": _sget(audit, "time_range_start"),
            "time_range_end": _sget(audit, "time_range_end"),
        }

    n_samples = _sget(summary, "n_samples") or _sget(data_quality, "clean_rows") or _sget(audit, "output_rows")
    name = data_name or _sget(data_quality, "target_col") or "时间序列"
    return {
        "data_name": name,
        "freq": cfg_get("freq"),
        "time_col": cfg_get("time_col"),
        "target_col": cfg_get("target_col"),
        "summary": summary,
        "recommendations": recommendations,
        "data_quality": data_quality,
        "aggregation": aggregation,
        "n_samples": n_samples,
    }


def _decide_overwrite(report_path: Path, force: bool) -> str:
    if force or not report_path.exists():
        return "write"
    try:
        head = report_path.read_text(encoding="utf-8")[:400]
    except OSError:
        return "write"
    return "skip" if AUTOGEN_MARKER not in head else "write"


