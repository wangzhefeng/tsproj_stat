def generate_eda_report(
    output_dir: str | Path,
    *,
    cfg: "AppConfig | None" = None,
    aggregation_result: "AggregationResult | None" = None,
    data_name: str | None = None,
    force: bool = False,
) -> str | None:
    """读取 output_dir 下已有 EDA JSON 产物，生成 EDA_REPORT.md，返回其绝对路径。

    纯函数（只读不重算）；输入缺失优雅降级；eda_summary.json 缺失则告警返回 None。
    覆盖策略：已存在且为手写（无 AUTOGEN_MARKER）默认跳过；自动生成的（含标记）会被刷新；
    force=True 一律覆盖。
    """
    out = Path(output_dir)
    ctx = _load_inputs(out, cfg, aggregation_result, data_name)
    if ctx.get("summary") is None:
        logger.warning("[EDA:report] eda_summary.json 缺失或不可读，跳过报告生成。")
        return None

    report_path = out / "EDA_REPORT.md"
    if _decide_overwrite(report_path, force) == "skip":
        logger.info(f"[EDA:report] {report_path} 已存在且为手写，跳过自动生成（如需覆盖请设 eda_report_overwrite=true）。")
        return str(report_path)

    blocks = [
        build_title(ctx),
        _exec_summary(ctx),
        build_section_1(ctx),
        build_section_2(ctx, out),
        build_section_3(ctx, out),
        build_section_4(ctx, out),
        build_section_5(ctx, out),
        build_section_6(ctx),
        build_section_7(ctx),
        build_section_8(ctx),
        build_footer(ctx),
    ]
    body = "\n\n".join("\n".join(b).rstrip() for b in blocks if b)
    content = f"{AUTOGEN_MARKER}\n\n{body}\n"
    report_path.write_text(content, encoding="utf-8")
    logger.info(f"[EDA:report] 生成 {report_path}")
    return str(report_path)
